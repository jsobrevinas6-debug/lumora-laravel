  /// Falls back to the built-in static catalog if the API is unreachable or empty.
  static Future<void> syncFromApi() async {
    if (!ApiConfig.useLiveApi) return;
    try {
      final fetched = await ApiService().fetchProducts();
      if (fetched.isNotEmpty) {
        _liveProducts = fetched;
        final deals = fetched.where((p) => p.isFlashDeal).toList();
        if (deals.isNotEmpty) {
          _liveFlashDeals = deals;
        }
        catalogVersion.value++;
      }
    } catch (_) {}
  }

